import { GRID_CACHE_SECONDS } from "../constants";
import type { GridResponse, HourIntensity } from "../types";
import { EiaError, fetchFuelMix } from "./eia";
import fallbackJson from "./fallback.json";
import { patternForecast } from "./forecast";
import { computeIntensity } from "./intensity";

// Builds the GridResponse for GET /api/grid. Measured hours are cached in
// memory for GRID_CACHE_SECONDS; the pattern forecast is recomputed on every
// call so it always starts at the current hour.

const RECENT_HOURS = 48;

// EIA answers a new day's query in ~60 s, then the identical query in < 1 s.
// The request path gives up after EIA_TIMEOUT_MS, so a background fetch with
// a longer deadline completes the slow first query and caches live data.
// Fallback is cached briefly so the next request picks that up soon.
const FALLBACK_CACHE_SECONDS = 120;
const BACKGROUND_TIMEOUT_MS = 90_000;

// Real ISNE snapshot (measured hours), regenerated by fallback.build.test.ts.
const FALLBACK = fallbackJson as HourIntensity[];

type Measured = { measured: HourIntensity[]; source: GridResponse["source"] };
type Fetcher = typeof fetchFuelMix;

let cache: (Measured & { expiresAt: number }) | null = null;
let inFlight: Promise<Measured> | null = null;
let background: Promise<void> | null = null;
let lastBackgroundAt = -Infinity;

export function resetGridCache() {
  cache = null;
  inFlight = null;
  background = null;
  lastBackgroundAt = -Infinity;
}

function cacheFor(result: Measured, now: Date) {
  const seconds = result.source === "live" ? GRID_CACHE_SECONDS : FALLBACK_CACHE_SECONDS;
  cache = { ...result, expiresAt: now.getTime() + seconds * 1000 };
}

// Starts one long-deadline EIA fetch, at most once per FALLBACK_CACHE_SECONDS
// (so a bad key doesn't call EIA on every request). Returns null when skipped.
// The promise never rejects; the route hands it to after().
export function refreshInBackground(
  now: Date,
  fetcher: Fetcher = fetchFuelMix,
): Promise<void> | null {
  if (background || now.getTime() - lastBackgroundAt < FALLBACK_CACHE_SECONDS * 1000) {
    return null;
  }
  lastBackgroundAt = now.getTime();
  background = fetcher({ now, timeoutMs: BACKGROUND_TIMEOUT_MS })
    .then((rows) => {
      const measured = computeIntensity(rows);
      if (measured.length === 0) return;
      cacheFor({ measured, source: "live" }, now);
    })
    .catch((err: unknown) => {
      const kind = err instanceof EiaError ? err.kind : "unknown error";
      console.warn(`Background EIA refresh failed (${kind})`);
    })
    .finally(() => {
      background = null;
    });
  return background;
}

async function loadMeasured(now: Date, fetcher: Fetcher): Promise<Measured> {
  try {
    const measured = computeIntensity(await fetcher({ now }));
    if (measured.length > 0) return { measured, source: "live" };
    console.warn("EIA returned no usable hours; serving fallback grid data");
  } catch (err) {
    if (!(err instanceof EiaError)) throw err;
    console.warn(`EIA unavailable (${err.kind}); serving fallback grid data`);
  }
  return { measured: FALLBACK, source: "fallback" };
}

// Concurrent requests share one EIA call. Fallback results are cached too,
// so requests don't each wait out the EIA timeout.
async function getMeasured(now: Date, fetcher: Fetcher): Promise<Measured> {
  if (cache && now.getTime() < cache.expiresAt) return cache;
  inFlight ??= loadMeasured(now, fetcher)
    .then((result) => {
      cacheFor(result, now);
      return result;
    })
    .finally(() => {
      inFlight = null;
    });
  return inFlight;
}

export async function getGrid(
  now: Date,
  fetcher: Fetcher = fetchFuelMix,
): Promise<GridResponse> {
  const { measured, source } = await getMeasured(now, fetcher);
  // Gap hours (latest measured → now) are not part of the response.
  const { forecast } = patternForecast(measured, now);
  const nowIso = now.toISOString();
  return {
    region: "ISNE",
    generatedAt: nowIso,
    forecastMadeAt: nowIso,
    latestDataHour: measured[measured.length - 1].hourStart,
    source,
    recent: measured.slice(-RECENT_HOURS),
    forecast,
  };
}
